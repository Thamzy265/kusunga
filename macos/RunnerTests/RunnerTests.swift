/// A pasteboard we control, that also records whether anyone read the text.
final class FakePasteboard: PasteboardReading {
  var changeCount = 0
  var typeIdentifiers: [String] = []
  var text: String? = nil
  private(set) var textReads = 0
  var onRead: (() -> Void)? = nil

  func plainString() -> String? {
    textReads += 1
    onRead?()
    return text
  }

  /// Simulates another app copying.
  func copy(_ text: String?, types: [String] = ["public.utf8-plain-text"]) {
    changeCount += 1
    self.text = text
    typeIdentifiers = types
  }
}

