  }
}

class ClipboardPollerTests: XCTestCase {
  var pasteboard: FakePasteboard!
  var events: [[String: Any]]!
  var poller: ClipboardPoller!

  override func setUp() {
    pasteboard = FakePasteboard()
    events = []
    poller = ClipboardPoller(pasteboard: pasteboard) { [unowned self] in self.events.append($0) }
    poller.prime()
  }

  func testWhatWasOnTheClipboardBeforeStartingIsNotReported() {
    let pb = FakePasteboard()
    pb.copy("already there")
    var got: [[String: Any]] = []
    let p = ClipboardPoller(pasteboard: pb) { got.append($0) }
    p.prime()
    p.tick()
    XCTAssertTrue(got.isEmpty)
    XCTAssertEqual(pb.textReads, 0)
  }

  func testNoChangeMeansNoReadAndNoEvent() {
    poller.tick()
    poller.tick()
    XCTAssertTrue(events.isEmpty)
    XCTAssertEqual(pasteboard.textReads, 0)
  }

  func testPlainTextIsReportedOnceUntilItChanges() {
    pasteboard.copy("hello")
    poller.tick()
    poller.tick()
    XCTAssertEqual(events.count, 1)
    XCTAssertEqual(events[0]["type"] as? String, "text")
    XCTAssertEqual(events[0]["text"] as? String, "hello")
  }

  func testSecretMarkedCopyIsNeverRead() {
    for marker in [
      "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
      "org.nspasteboard.AutoGeneratedType",
    ] {
      pasteboard.copy("hunter2", types: ["public.utf8-plain-text", marker])
      poller.tick()
    }
    XCTAssertEqual(pasteboard.textReads, 0, "the text of a secret copy must never be read")
    XCTAssertEqual(events.count, 3)
    for e in events {
      XCTAssertEqual(e["type"] as? String, "concealed")
      XCTAssertNil(e["text"])
    }
  }

  func testCopyWithoutTextIsIgnoredWithoutReading() {
    pasteboard.copy(nil, types: ["public.png"])
    poller.tick()
    XCTAssertTrue(events.isEmpty)
    XCTAssertEqual(pasteboard.textReads, 0)
  }

  func testTextOverOneMegabyteIsReportedAsTooLargeWithoutTheText() {
    pasteboard.copy(String(repeating: "x", count: ClipboardPolicy.maxBytes + 1))
    poller.tick()
    XCTAssertEqual(events.count, 1)
    XCTAssertEqual(events[0]["type"] as? String, "tooLarge")
    XCTAssertNil(events[0]["text"])
  }

  func testTextOfExactlyOneMegabyteIsReported() {
    pasteboard.copy(String(repeating: "x", count: ClipboardPolicy.maxBytes))
    poller.tick()
    XCTAssertEqual(events[0]["type"] as? String, "text")
  }

  func testACopyThatChangesWhileBeingReadIsDroppedAndCaughtNextTick() {
    // The clipboard changes between the type check and the read: the text we
    // got may belong to a newer, possibly secret, copy.
    pasteboard.copy("first")
    pasteboard.onRead = { [unowned self] in
      self.pasteboard.copy("second", types: ["org.nspasteboard.ConcealedType"])
    }
    poller.tick()
    XCTAssertTrue(events.isEmpty)
    pasteboard.onRead = nil
    poller.tick()
    XCTAssertEqual(events.count, 1)
    XCTAssertEqual(events[0]["type"] as? String, "concealed")
  }
}

class TerminationCoordinatorTests: XCTestCase {
  func testFlushesBeforeReplyingAndRepliesOnce() {
    var order: [String] = []
    var finishFlush: (() -> Void)?
    let c = TerminationCoordinator(
      flush: { done in
        order.append("flush")
        finishFlush = done
      },
      reply: { order.append("reply") },
      timeout: 60)
    XCTAssertEqual(c.begin(), .terminateLater)
    XCTAssertEqual(order, ["flush"])
    finishFlush?()
    finishFlush?()
    XCTAssertEqual(order, ["flush", "reply"])
  }

  func testRepliesAfterTheTimeoutIfDartNeverAnswers() {
    let replied = expectation(description: "replied")
    let c = TerminationCoordinator(flush: { _ in }, reply: { replied.fulfill() }, timeout: 0.1)
    _ = c.begin()
    wait(for: [replied], timeout: 2)
  }

  func testWithNoDartSideItTerminatesAtOnce() {
    let c = TerminationCoordinator(flush: nil, reply: { XCTFail("no reply needed") }, timeout: 60)
    XCTAssertEqual(c.begin(), .terminateNow)
  }

  func testASecondRequestWhileFlushingDoesNotFlushAgain() {
    var flushes = 0
    let c = TerminationCoordinator(flush: { _ in flushes += 1 }, reply: {}, timeout: 60)
    _ = c.begin()
    XCTAssertEqual(c.begin(), .terminateLater)
    XCTAssertEqual(flushes, 1)
  }
}

