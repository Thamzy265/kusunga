/// A pasteboard that can change between the two reads the poller makes, like
/// another app copying in the middle of a tick.
final class RacyPasteboard: PasteboardReading {
  var changeCount = 0
  var types: [String] = []
  var text: String? = nil
  private(set) var textReads = 0
  private(set) var typeReads = 0
  /// Runs on every read of the types, before the answer is returned.
  var onTypes: ((RacyPasteboard) -> Void)? = nil

  var typeIdentifiers: [String] {
    typeReads += 1
    onTypes?(self)
    return types
  }

  func plainString() -> String? {
    textReads += 1
    return text
  }

  func copy(_ text: String?, types: [String]) {
    changeCount += 1
    self.text = text
    self.types = types
  }
}

class ClipboardPollerEdgeTests: XCTestCase {
  var pasteboard: FakePasteboard!
  var events: [[String: Any]]!
  var poller: ClipboardPoller!

  let secretTypes = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
  ]

  override func setUp() {
    pasteboard = FakePasteboard()
    events = []
    poller = ClipboardPoller(pasteboard: pasteboard) { [unowned self] in self.events.append($0) }
    poller.prime()
  }

  private func texts() -> [String] { events.compactMap { $0["text"] as? String } }
  private func kinds() -> [String] { events.compactMap { $0["type"] as? String } }

  // Secret markers combined with every other kind of text type.

  func testSecretMarkerWithEveryPlainTextTypeIsNeverRead() {
    let textTypes = [
      "public.utf8-plain-text", "public.utf16-plain-text", "NSStringPboardType",
      "public.html", "public.rtf", "public.url", "com.apple.traditional-mac-plain-text",
    ]
    for marker in secretTypes {
      // One text type, then all of them, in both orders, marker first and last.
      for combo in [[textTypes[0]], textTypes, textTypes.reversed() as [String]] {
        for markerFirst in [true, false] {
          let types = markerFirst ? [marker] + combo : combo + [marker]
          pasteboard.copy("hunter2-\(marker)", types: types)
          poller.tick()
        }
      }
    }
    XCTAssertEqual(pasteboard.textReads, 0, "no text of a secret copy may ever be read")
    XCTAssertTrue(texts().isEmpty)
    XCTAssertTrue(kinds().allSatisfy { $0 == "concealed" })
    XCTAssertEqual(kinds().count, 3 * 3 * 2)
  }

  func testSecretMarkerAloneAndWithNonTextTypes() {
    pasteboard.copy(nil, types: ["org.nspasteboard.ConcealedType"])
    poller.tick()
    pasteboard.copy(nil, types: ["public.png", "org.nspasteboard.TransientType", "public.tiff"])
    poller.tick()
    XCTAssertEqual(kinds(), ["concealed", "concealed"])
    XCTAssertEqual(pasteboard.textReads, 0)
  }

  func testAllThreeMarkersTogetherIsOneConcealedEvent() {
    pasteboard.copy("x", types: ["public.utf8-plain-text"] + secretTypes)
    poller.tick()
    poller.tick()
    XCTAssertEqual(kinds(), ["concealed"])
    XCTAssertEqual(pasteboard.textReads, 0)
  }

  func testConcealedEventHasNothingButItsType() {
    pasteboard.copy("hunter2", types: ["public.utf8-plain-text", secretTypes[0]])
    poller.tick()
    XCTAssertEqual(events.count, 1)
    XCTAssertEqual(Set(events[0].keys), ["type"])
  }

  func testTheNextOrdinaryCopyAfterASecretOneIsReported() {
    pasteboard.copy("secret", types: ["public.utf8-plain-text", secretTypes[1]])
    poller.tick()
    pasteboard.copy("ordinary", types: ["public.utf8-plain-text"])
    poller.tick()
    XCTAssertEqual(texts(), ["ordinary"])
    XCTAssertEqual(pasteboard.textReads, 1)
  }

  func testSameTextCopiedAsSecretThenPlainIsReportedOnceAsPlain() {
    pasteboard.copy("same", types: ["public.utf8-plain-text", secretTypes[0]])
    poller.tick()
    pasteboard.copy("same", types: ["public.utf8-plain-text"])
    poller.tick()
    XCTAssertEqual(kinds(), ["concealed", "text"])
  }

  // Empty and non-text pasteboards.

  func testEmptyPasteboardChangeIsIgnoredWithoutReading() {
    pasteboard.copy(nil, types: [])
    poller.tick()
    poller.tick()
    XCTAssertTrue(events.isEmpty)
    XCTAssertEqual(pasteboard.textReads, 0)
  }

  func testNonTextOnlyCopiesAreIgnoredWithoutReading() {
    for types in [
      ["public.png"], ["public.tiff", "public.jpeg"], ["public.file-url"],
      ["com.apple.pasteboard.promised-file-url"], ["public.pdf", "com.adobe.pdf"],
      ["dyn.ah62d4rv4gu8y6y4grf0gn5xbrzw1gydcr7u1e3cytf2gn"],
    ] {
      pasteboard.copy(nil, types: types)
      poller.tick()
    }
    XCTAssertTrue(events.isEmpty)
    XCTAssertEqual(pasteboard.textReads, 0)
  }

  func testRichTextWithoutPlainTextIsNotSavedOrRead() {
    // Rich text only (no plain string type): outside the M1.2 scope.
    pasteboard.copy("<b>x</b>", types: ["public.html", "public.rtf"])
    poller.tick()
    XCTAssertTrue(events.isEmpty)
    XCTAssertEqual(pasteboard.textReads, 0)
  }

  // Changed for QA finding AC1 (copies lost at 0.6 s): a copy whose text is not
  // readable yet is retried on the next ticks, at most maxTicksToWait times,
  // instead of being read once and dropped.
  func testPlainTypeButNoStringProducesNoEventAndIsReadAtMostEightTimes() {
    pasteboard.copy(nil, types: ["public.utf8-plain-text"])
    for _ in 0..<20 { poller.tick() }
    XCTAssertTrue(events.isEmpty)
    XCTAssertEqual(pasteboard.textReads, ClipboardPoller.maxTicksToWait)
  }

  func testEmptyStringIsPassedOnForDartToIgnore() {
    // Locks the split of work: native does not judge empty or whitespace-only
    // text; Dart ignores it (history_service_test).
    pasteboard.copy("", types: ["public.utf8-plain-text"])
    poller.tick()
    pasteboard.copy("  \n\t ", types: ["public.utf8-plain-text"])
    poller.tick()
    XCTAssertEqual(texts(), ["", "  \n\t "])
  }

  func testTextWithNulAndControlCharactersIsPassedThroughWhole() {
    let odd = "\u{0}start\u{202E}rtl\u{7}\u{85}end\u{2028}"
    pasteboard.copy(odd, types: ["public.utf8-plain-text"])
    poller.tick()
    XCTAssertEqual(texts(), [odd])
  }

  // changeCount behaviour.

  func testChangeCountWrapAroundIsSeenAsAChange() {
    pasteboard.changeCount = Int.max
    poller.prime()
    pasteboard.text = "after wrap"
    pasteboard.typeIdentifiers = ["public.utf8-plain-text"]
    pasteboard.changeCount = Int.min  // wrapped
    poller.tick()
    XCTAssertEqual(texts(), ["after wrap"])
    poller.tick()
    XCTAssertEqual(texts().count, 1)
  }

  func testChangeCountGoingDownIsAlsoAChange() {
    pasteboard.changeCount = 50
    poller.prime()
    pasteboard.text = "reset"
    pasteboard.typeIdentifiers = ["public.utf8-plain-text"]
    pasteboard.changeCount = 3
    poller.tick()
    XCTAssertEqual(texts(), ["reset"])
  }

  func testChangeCountZeroAndNegativeValuesWork() {
    for count in [0, -1, Int.min, Int.max] {
      pasteboard.changeCount = count
      poller.prime()
      pasteboard.text = "at \(count)"
      pasteboard.typeIdentifiers = ["public.utf8-plain-text"]
      pasteboard.changeCount = count == 0 ? 1 : 0
      poller.tick()
    }
    XCTAssertEqual(texts().count, 4)
  }

  func testSecretCopyAfterWrapAroundIsStillNeverRead() {
    pasteboard.changeCount = Int.max
    poller.prime()
    pasteboard.text = "hunter2"
    pasteboard.typeIdentifiers = ["public.utf8-plain-text", secretTypes[0]]
    pasteboard.changeCount = Int.min
    poller.tick()
    XCTAssertEqual(pasteboard.textReads, 0)
    XCTAssertEqual(kinds(), ["concealed"])
  }

  func testTheSameTextCopiedTwiceIsReportedTwice() {
    // Duplicates are handled in Dart; native must not swallow a real copy.
    pasteboard.copy("again", types: ["public.utf8-plain-text"])
    poller.tick()
    pasteboard.copy("again", types: ["public.utf8-plain-text"])
    poller.tick()
    XCTAssertEqual(texts(), ["again", "again"])
  }

  func testStartingWithASecretAlreadyOnTheClipboardReportsNothing() {
    let pb = FakePasteboard()
    pb.copy("old secret", types: ["public.utf8-plain-text", secretTypes[0]])
    var got: [[String: Any]] = []
    let p = ClipboardPoller(pasteboard: pb) { got.append($0) }
    p.prime()
    p.tick()
    XCTAssertTrue(got.isEmpty)
    XCTAssertEqual(pb.textReads, 0)
  }

  // Size boundaries, in UTF-8 bytes (the same as the Dart and C++ sides).
  // Lead decision (M1.2 fixes): the cap is 1 MiB of UTF-8 bytes, not
  // characters; this test used to count UTF-16 units.

  func testLimitCountsUtf8Bytes() {
    let max = ClipboardPolicy.maxBytes
    let text = ["public.utf8-plain-text"]
    // 4 bytes each: max / 4 fit exactly, one more does not.
    pasteboard.copy(String(repeating: "\u{1F600}", count: max / 4), types: text)
    poller.tick()
    pasteboard.copy(String(repeating: "\u{1F600}", count: max / 4 + 1), types: text)
    poller.tick()
    // 3 bytes each: 349,525 fit (1,048,575 bytes), one more does not.
    pasteboard.copy(String(repeating: "\u{20AC}", count: max / 3), types: text)
    poller.tick()
    pasteboard.copy(String(repeating: "\u{20AC}", count: max / 3 + 1), types: text)
    poller.tick()
    // "e" plus a combining accent: 3 bytes.
    pasteboard.copy(String(repeating: "e\u{301}", count: max / 3), types: text)
    poller.tick()
    pasteboard.copy(String(repeating: "e\u{301}", count: max / 3 + 1), types: text)
    poller.tick()
    XCTAssertEqual(
      kinds(), ["text", "tooLarge", "text", "tooLarge", "text", "tooLarge"])
    for e in events where e["type"] as? String == "tooLarge" {
      XCTAssertNil(e["text"], "no part of a large copy is passed on")
    }
  }

  func testSecretAndHugeIsConcealedNotTooLargeAndNeverRead() {
    pasteboard.copy(
      String(repeating: "x", count: ClipboardPolicy.maxBytes + 10),
      types: ["public.utf8-plain-text", secretTypes[0]])
    poller.tick()
    XCTAssertEqual(kinds(), ["concealed"])
    XCTAssertEqual(pasteboard.textReads, 0)
  }

  func testLimitAndTypeConstantsMatchTheDesign() {
    XCTAssertEqual(ClipboardPolicy.maxBytes, 1_048_576)
    XCTAssertEqual(ClipboardPolicy.plainTextType, "public.utf8-plain-text")
    XCTAssertEqual(
      ClipboardPolicy.secretTypes,
      [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
      ])
  }

  // Races between the two reads of one tick.

  func testSecretCopyThenAPlainCopyBeforeTheTypesAreReadLeaksNothing() {
    let pb = RacyPasteboard()
    var got: [[String: Any]] = []
    let p = ClipboardPoller(pasteboard: pb) { got.append($0) }
    p.prime()
    pb.copy("hunter2", types: ["public.utf8-plain-text", secretTypes[0]])
    // After the poller read the count, another app copies plain text.
    pb.onTypes = { board in
      board.onTypes = nil
      board.copy("plain", types: ["public.utf8-plain-text"])
    }
    p.tick()
    XCTAssertFalse(
      got.contains { ($0["text"] as? String) == "hunter2" }, "the secret must not be reported")
    XCTAssertEqual(pb.textReads, 1)
    XCTAssertTrue(got.isEmpty, "text read for a changed count is dropped")
    p.tick()
    XCTAssertEqual(got.compactMap { $0["text"] as? String }, ["plain"])
  }

  func testPlainCopyThenASecretCopyBeforeTheTypesAreReadIsConcealed() {
    let pb = RacyPasteboard()
    var got: [[String: Any]] = []
    let p = ClipboardPoller(pasteboard: pb) { got.append($0) }
    p.prime()
    pb.copy("plain", types: ["public.utf8-plain-text"])
    pb.onTypes = { board in
      board.onTypes = nil
      board.copy("hunter2", types: ["public.utf8-plain-text", self.secretTypes[0]])
    }
    p.tick()
    XCTAssertEqual(pb.textReads, 0, "the secret copy's text is never read")
    XCTAssertFalse(got.contains { ($0["text"] as? String) != nil })
  }

  // A long random run: a secret copy's text can never come out.

  func testRandomCopiesNeverLeakASecretOrReadItsText() {
    var seed: UInt64 = 0x9E37_79B9_7F4A_7C15
    func next() -> Int {
      seed = seed &* 6_364_136_223_846_793_005 &+ 1_442_695_040_888_963_407
      return Int(truncatingIfNeeded: seed >> 33)
    }
    let pb = FakePasteboard()
    var got: [[String: Any]] = []
    let p = ClipboardPoller(pasteboard: pb) { got.append($0) }
    p.prime()
    var plainCopies = 0
    var secretCopies = 0
    for i in 0..<5000 {
      let roll = next() % 10
      switch roll {
      case 0, 1:
        pb.copy(
          "SECRET-\(i)", types: ["public.utf8-plain-text", secretTypes[next() % 3]])
        secretCopies += 1
      case 2:
        pb.copy(nil, types: ["public.png"])
      case 3:
        pb.copy(
          "SECRET-\(i)",
          types: [secretTypes[next() % 3], "public.html", "public.utf8-plain-text"])
        secretCopies += 1
      case 4:
        pb.copy("plain-\(i)", types: ["public.utf8-plain-text", "public.html"])
        plainCopies += 1
      case 5:
        pb.changeCount = pb.changeCount &+ 1  // a change we never see the type of
      default:
        pb.copy("plain-\(i)", types: ["public.utf8-plain-text"])
        plainCopies += 1
      }
      // Several copies can happen between two ticks.
      if next() % 3 != 0 { p.tick() }
    }
    p.tick()
    for e in got {
      if let text = e["text"] as? String {
        XCTAssertFalse(text.hasPrefix("SECRET-"), "leaked: \(text)")
      }
    }
    XCTAssertLessThanOrEqual(pb.textReads, plainCopies + 1, "secret text was read")
    XCTAssertGreaterThan(secretCopies, 100)
  }
}

class TerminationCoordinatorEdgeTests: XCTestCase {
  func testALateAnswerFromDartAfterTheTimeoutDoesNotReplyTwice() {
    var replies = 0
    var finishFlush: (() -> Void)?
    let timedOut = expectation(description: "timeout reply")
    let c = TerminationCoordinator(
      flush: { done in finishFlush = done },
      reply: {
        replies += 1
        if replies == 1 { timedOut.fulfill() }
      },
      timeout: 0.05)
    _ = c.begin()
    wait(for: [timedOut], timeout: 2)
    finishFlush?()
    finishFlush?()
    let later = expectation(description: "later")
    DispatchQueue.main.asyncAfter(deadline: .now() + 0.2) { later.fulfill() }
    wait(for: [later], timeout: 2)
    XCTAssertEqual(replies, 1)
  }

  func testTheTimeoutAfterAnAnswerDoesNotReplyAgain() {
    var replies = 0
    var finishFlush: (() -> Void)?
    let c = TerminationCoordinator(
      flush: { done in finishFlush = done }, reply: { replies += 1 }, timeout: 0.05)
    _ = c.begin()
    finishFlush?()
    XCTAssertEqual(replies, 1)
    let later = expectation(description: "after the timeout")
    DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) { later.fulfill() }
    wait(for: [later], timeout: 2)
    XCTAssertEqual(replies, 1)
  }

  func testManyQuitRequestsFlushOnceAndReplyOnce() {
    var flushes = 0
    var replies = 0
    var finishFlush: (() -> Void)?
    let c = TerminationCoordinator(
      flush: { done in
        flushes += 1
        finishFlush = done
      },
      reply: { replies += 1 }, timeout: 60)
    for _ in 0..<10 { XCTAssertEqual(c.begin(), .terminateLater) }
    finishFlush?()
    XCTAssertEqual(flushes, 1)
    XCTAssertEqual(replies, 1)
  }

  func testWithNoDartSideEveryRequestTerminatesAtOnceAndNothingIsScheduled() {
    var replies = 0
    let c = TerminationCoordinator(flush: nil, reply: { replies += 1 }, timeout: 0.05)
    XCTAssertEqual(c.begin(), .terminateNow)
    XCTAssertEqual(c.begin(), .terminateNow)
    let later = expectation(description: "later")
    DispatchQueue.main.asyncAfter(deadline: .now() + 0.2) { later.fulfill() }
    wait(for: [later], timeout: 2)
    XCTAssertEqual(replies, 0)
  }

  func testTheReplyComesOnlyAfterTheFlushAnswerNotBefore() {
    var replied = false
    var finishFlush: (() -> Void)?
    let c = TerminationCoordinator(
      flush: { done in finishFlush = done }, reply: { replied = true }, timeout: 60)
    XCTAssertEqual(c.begin(), .terminateLater)
    XCTAssertFalse(replied, "AppKit must not be told to quit while Dart is still saving")
    finishFlush?()
    XCTAssertTrue(replied)
  }
}

/// A copy whose text is not readable yet when the change count moves (pbcopy
/// declares the types first) must be retried on the next ticks, not dropped.
class ClipboardPollerRetryTests: XCTestCase {
  var pasteboard: FakePasteboard!
  var events: [[String: Any]]!
  var poller: ClipboardPoller!
  let textType = "public.utf8-plain-text"

  override func setUp() {
    pasteboard = FakePasteboard()
    events = []
    poller = ClipboardPoller(pasteboard: pasteboard) { [unowned self] in self.events.append($0) }
    poller.prime()
  }

  func testTextThatArrivesOneTickAfterTheCountChangedIsReported() {
    pasteboard.copy(nil, types: [textType])  // declared, not readable yet
    poller.tick()
    XCTAssertTrue(events.isEmpty)
    pasteboard.text = "arrived late"  // same change count
    poller.tick()
    XCTAssertTrue(events.isEmpty, "read on a retry: held until the next tick confirms")
    poller.tick()
    XCTAssertEqual(events.count, 1)
    XCTAssertEqual(events[0]["text"] as? String, "arrived late")
    poller.tick()
    XCTAssertEqual(events.count, 1, "reported once")
  }

  func testTypesThatArriveLaterAreReported() {
    pasteboard.copy(nil, types: [])
    poller.tick()
    pasteboard.typeIdentifiers = [textType]
    pasteboard.text = "types came late"
    poller.tick()
    poller.tick()
    XCTAssertEqual(events.count, 1)
  }

  func testTextThatNeverArrivesGivesUpAfterEightTicks() {
