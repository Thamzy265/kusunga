import Cocoa

/// The part of NSPasteboard the watcher uses, so tests can replace it.
protocol PasteboardReading: AnyObject {
  var changeCount: Int { get }
  var typeIdentifiers: [String] { get }
  /// Reads the plain text. Only called after the type check has passed.
  func plainString() -> String?
}

extension NSPasteboard: PasteboardReading {
  var typeIdentifiers: [String] { (types ?? []).map { $0.rawValue } }
  func plainString() -> String? { string(forType: .string) }
}

enum ClipboardPolicy {
  /// Password managers and the system mark secret copies with these types
  /// (nspasteboard.org). A copy with any of them is never read or saved.
  static let secretTypes: Set<String> = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
  ]

  /// Longest text we keep: 1 MiB of UTF-8 bytes (the same limit as the Dart
  /// and Windows sides).
  static let maxBytes = 1_048_576

  static let plainTextType = "public.utf8-plain-text"

  /// Kusunga's own marker on a copy the picker pasted. Any app can add it, so
  /// it never skips the secret check; it only tells Dart "if this text is
  /// already saved, move it to the top".
  static let ownMarkerType = "com.wnasoni.kusunga.self"

  static func isSecret(_ types: [String]) -> Bool {
    types.contains { secretTypes.contains($0) }
  }
}

/// Kusunga's own clipboard changes that must not become history: a pasted or
/// copied snippet (PM decision D1, M1.4). A change is matched by the change
/// count Kusunga itself got back right after writing, which no other app can
/// fake; never by the marker type, which any app can add.
final class OwnClipboardChanges {
  static let shared = OwnClipboardChanges()

  private var recorded: Int?

  /// Called right after Kusunga wrote, before the run loop can turn.
  func record(_ changeCount: Int) { recorded = changeCount }

  /// True once, for exactly the recorded change. Any check uses the record
  /// up: a change count that moved on means someone else wrote after us.
  func consume(_ changeCount: Int) -> Bool {
    guard let mine = recorded else { return false }
    recorded = nil
    return mine == changeCount
  }
}

/// Looks at the pasteboard when its change count moves. Reading the change
/// count does not read any content. On a change it checks the types first and
/// reads the text only if the copy is not marked secret.
final class ClipboardPoller {
  private let pasteboard: PasteboardReading
  private let emit: ([String: Any]) -> Void
  private var lastCount: Int
  private let ownChanges: OwnClipboardChanges?

  /// False when the user has not chosen "Allow" for pasteboard access (ask or
  /// deny): every read can raise a system alert, so a copy is read once only.
  private let mayRetry: () -> Bool

  init(
    pasteboard: PasteboardReading, mayRetry: @escaping () -> Bool = { true },
    ownChanges: OwnClipboardChanges? = nil,
    emit: @escaping ([String: Any]) -> Void
  ) {
    self.pasteboard = pasteboard
    self.mayRetry = mayRetry
    self.ownChanges = ownChanges
    self.emit = emit
    self.lastCount = pasteboard.changeCount
  }

  /// Forgets whatever is on the clipboard now: it was copied before we
  /// started, so we neither read nor report it.
  func prime() {
    lastCount = pasteboard.changeCount
  }

  /// How many ticks (250 ms each, so about 2 s) to wait for the text of a copy
  /// whose change count has moved. Some tools (pbcopy) declare the types a
  /// moment before the text can be read.
  static let maxTicksToWait = 8

  private var waiting = false
  private var ticksLeft = 0
  private var isRetry = false
  /// Text read on a retry tick, held until the next tick confirms that the
  /// types and the change count did not move (so a secret marker that arrives
  /// just after the text is still seen before anything is sent).
  private var held: (text: String, types: [String])?

  func tick() {
    let count = pasteboard.changeCount
    if count != lastCount {
      lastCount = count
      // Kusunga's own change (a snippet): not read, not reported.
      if ownChanges?.consume(count) == true {
        waiting = false
        held = nil
        return
      }
      waiting = true
      ticksLeft = ClipboardPoller.maxTicksToWait
      isRetry = false
      held = nil
    }
    guard waiting else { return }

    // The secret check is repeated on every try, before any read.
    let types = pasteboard.typeIdentifiers
    if ClipboardPolicy.isSecret(types) {
      waiting = false
      held = nil
      emit(["type": "concealed"])
      return
    }

    if let held = held {
      // The confirming tick: nothing moved since the text was read, so send it.
      if held.types == types {
        waiting = false
        self.held = nil
        send(held.text, types: held.types)
        return
      }
      // The types changed without a secret marker (a writer added a type):
      // read again and confirm one tick later, within the same bound.
      self.held = nil
      ticksLeft -= 1
      if ticksLeft <= 0 {
        waiting = false
        return
      }
      if types.contains(ClipboardPolicy.plainTextType) {
        let text = pasteboard.plainString()
        if pasteboard.changeCount != count { return }
        if let text = text { self.held = (text, types) }
      }
      return
    }

    if types.contains(ClipboardPolicy.plainTextType) {
      let text = pasteboard.plainString()
      // The clipboard changed while we read: the text may belong to a newer copy
      // whose types we have not checked. Drop it; the next tick starts over.
      if pasteboard.changeCount != count { return }
      if let text = text {
        if isRetry {
          held = (text, types)  // confirmed on the next tick
        } else {
          waiting = false
          send(text, types: types)
        }
        return
      }
    }

    // Not readable yet (or not text at all): try again on the next ticks, then
    // give up on this copy. With "Ask" or "Don't Allow" there is no retry.
    isRetry = true
    ticksLeft -= 1
    if ticksLeft <= 0 || !mayRetry() { waiting = false }
  }

  private func send(_ text: String, types: [String]) {
    if text.utf8.count > ClipboardPolicy.maxBytes {
      emit(["type": "tooLarge"])
    } else if types.contains(ClipboardPolicy.ownMarkerType) {
      emit(["type": "text", "text": text, "own": true])
    } else {
      emit(["type": "text", "text": text])
    }
  }
}
