import Cocoa

/// The part of NSPasteboard the watcher uses, so tests can replace it.
protocol PasteboardReading: AnyObject {
  var changeCount: Int { get }
  var typeIdentifiers: [String] { get }
  /// Reads the plain text. Only called after the type check has passed.
  func plainString() -> String?
}

extension NSPasteboard: PasteboardReading {
  var typeIdentifiers: [String] { (types ?? []).map { $0.rawValue } }
  func plainString() -> String? { string(forType: .string) }
}

enum ClipboardPolicy {
  /// Password managers and the system mark secret copies with these types
  /// (nspasteboard.org). A copy with any of them is never read or saved.
  static let secretTypes: Set<String> = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
  ]

  /// Longest text we keep: 1 MiB of UTF-8 bytes (the same limit as the Dart
  /// and Windows sides).
  static let maxBytes = 1_048_576

  static let plainTextType = "public.utf8-plain-text"

  static func isSecret(_ types: [String]) -> Bool {
    types.contains { secretTypes.contains($0) }
  }
}

/// Looks at the pasteboard when its change count moves. Reading the change
/// count does not read any content. On a change it checks the types first and
/// reads the text only if the copy is not marked secret.
final class ClipboardPoller {
  private let pasteboard: PasteboardReading
  private let emit: ([String: Any]) -> Void
  private var lastCount: Int

  init(pasteboard: PasteboardReading, emit: @escaping ([String: Any]) -> Void) {
    self.pasteboard = pasteboard
    self.emit = emit
    self.lastCount = pasteboard.changeCount
  }

  /// Forgets whatever is on the clipboard now: it was copied before we
  /// started, so we neither read nor report it.
  func prime() {
    lastCount = pasteboard.changeCount
  }

  /// How many ticks (250 ms each, so about 2 s) to wait for the text of a copy
  /// whose change count has moved. Some tools (pbcopy) declare the types a
  /// moment before the text can be read.
  static let maxTicksToWait = 8

  private var waiting = false
  private var ticksLeft = 0

  func tick() {
    let count = pasteboard.changeCount
    if count != lastCount {
      lastCount = count
      waiting = true
      ticksLeft = ClipboardPoller.maxTicksToWait
    }
    guard waiting else { return }

    // The secret check is repeated on every try, before any read.
    let types = pasteboard.typeIdentifiers
    if ClipboardPolicy.isSecret(types) {
      waiting = false
      emit(["type": "concealed"])
      return
    }

    if types.contains(ClipboardPolicy.plainTextType) {
      let text = pasteboard.plainString()
      // The clipboard changed while we read: the text may belong to a newer copy
      // whose types we have not checked. Drop it; the next tick starts over.
      if pasteboard.changeCount != count { return }
      if let text = text {
        waiting = false
        if text.utf8.count > ClipboardPolicy.maxBytes {
          emit(["type": "tooLarge"])
        } else {
          emit(["type": "text", "text": text])
        }
        return
      }
    }

    // Not readable yet (or not text at all): try again on the next ticks, then
    // give up on this copy.
    ticksLeft -= 1
    if ticksLeft <= 0 { waiting = false }
  }
}
